from typing import Any, List, Literal, Optional
from uuid import UUID

from pydantic import BaseModel, Field, field_validator

Difficulty = Literal["easy", "medium", "hard"]
QuestionType = Literal["multiple_choice", "true_false", "short_answer", "essay"]


# ── Public API schemas ──────────────────────────────────────────────


class QuestionGenerateRequest(BaseModel):
    document_id: UUID = Field(..., description="UUID of an indexed document")
    number_of_questions: int = Field(5, ge=1, le=20)
    difficulty: Difficulty = "medium"
    question_type: QuestionType = "short_answer"


class GeneratedQuestion(BaseModel):
    question_id: str = Field(..., description="Generated by the backend, never by the LLM")
    question: str
    expected_answer: str
    difficulty: Difficulty
    type: QuestionType
    source_chunks: List[str] = Field(
        default_factory=list,
        description="Derived by the backend from ChromaDB retrieval, never by the LLM",
    )
    # Extensible fields — only populated for multiple_choice / true_false.
    options: Optional[List[str]] = None
    correct_answer: Optional[str] = None


class QuestionGenerationResponse(BaseModel):
    document_id: UUID
    questions: List[GeneratedQuestion]


# -- Exam matrix (Module 1 sends subject + a count/difficulty/type matrix, reviews the result, then saves it) --

MAX_MATRIX_ITEMS = 12


class ExamMatrixItem(BaseModel):
    """One row of the exam matrix: ``count`` questions of one type and one difficulty."""

    question_type: QuestionType
    difficulty: Difficulty
    count: int = Field(..., ge=1, le=20)


class ExamMatrixRequest(BaseModel):
    document_id: UUID = Field(..., description="UUID of an indexed document")
    subject: Optional[str] = Field(
        default=None, max_length=200,
        description="Subject/course label from Module 1. Echoed back for traceability only; it is NOT sent to "
                    "the model, so it cannot influence or inject into the prompt.",
    )
    items: List[ExamMatrixItem] = Field(..., min_length=1, max_length=MAX_MATRIX_ITEMS)

    @field_validator("subject")
    @classmethod
    def _clean_subject(cls, v: Optional[str]) -> Optional[str]:
        if v is None:
            return None
        v = " ".join(v.split())
        return v or None

    @field_validator("items")
    @classmethod
    def _total_within_limit(cls, items: List[ExamMatrixItem]) -> List[ExamMatrixItem]:
        from app.core.config import get_settings

        limit = get_settings().max_matrix_questions
        if sum(i.count for i in items) > limit:
            raise ValueError(f"the matrix requests more than the allowed {limit} questions in total")
        return items


class MatrixQuestion(GeneratedQuestion):
    matrix_item: int = Field(..., ge=0, description="Index of the request item this question belongs to")


class ExamMatrixItemResult(BaseModel):
    index: int
    question_type: QuestionType
    difficulty: Difficulty
    requested: int
    generated: int
    status: Literal["ok", "partial", "failed"]
    error_code: Optional[str] = Field(default=None, description="Set when status is failed")


class ExamMatrixResponse(BaseModel):
    document_id: UUID
    subject: Optional[str] = None
    requested_total: int
    generated_total: int
    complete: bool = Field(..., description="True only when every item produced exactly the requested count")
    items: List[ExamMatrixItemResult]
    questions: List[MatrixQuestion]


# Backward-compatible aliases (names used before Phase 6).
QuestionGenerationRequest = QuestionGenerateRequest
QuestionResponse = GeneratedQuestion
QuestionListResponse = QuestionGenerationResponse


# ── Internal schemas (validate untrusted LLM JSON) ──────────────────


class LLMGeneratedQuestion(BaseModel):
    """One question as returned by the LLM.

    Unknown keys (e.g. ``source_chunks``, ``question_id``) are ignored on purpose:
    the backend never trusts them.
    """

    question: str
    expected_answer: str
    difficulty: Difficulty
    type: QuestionType
    options: Optional[List[str]] = None
    correct_answer: Optional[str] = None


class LLMQuestionGenerationResult(BaseModel):
    """Container for LLM output.  Malformed items are dropped individually so one
    bad question does not discard the valid ones."""

    questions: List[LLMGeneratedQuestion]

    @field_validator("questions", mode="before")
    @classmethod
    def _drop_malformed_items(cls, value: Any) -> Any:
        if not isinstance(value, list):
            return value  # let normal validation fail
        valid: list[LLMGeneratedQuestion] = []
        for item in value:
            try:
                valid.append(LLMGeneratedQuestion.model_validate(item))
            except Exception:
                continue
        return valid
