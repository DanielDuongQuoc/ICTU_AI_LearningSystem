"""Phase 4 — RAG retrieval schemas."""

from typing import Optional

from pydantic import BaseModel, Field


class RAGRetrievalRequest(BaseModel):
    document_id: str = Field(..., min_length=1, description="Document to retrieve from")
    question: str = Field(..., description="Natural-language question")
    top_k: Optional[int] = Field(
        default=None,
        description="Max chunks to retrieve (1..MAX_TOP_K). Defaults to TOP_K setting.",
    )


class RAGChunk(BaseModel):
    chunk_id: str
    document_id: str
    page: Optional[int] = None
    source: str = ""
    score: float = Field(..., description="Cosine similarity (1 - cosine distance), higher is better")
    text: str


class RAGSource(BaseModel):
    chunk_id: str
    document_id: str
    page: Optional[int] = None
    source: str = ""
    score: float


class RAGRetrievalResponse(BaseModel):
    document_id: str
    question: str
    insufficient_context: bool
    chunks: list[RAGChunk]
    context: str
    sources: list[RAGSource]


class RAGAnswerResponse(BaseModel):
    document_id: str
    question: str
    answer: str
    insufficient_context: bool
    sources: list[RAGSource] = Field(
        default_factory=list,
        description="Taken from retrieval (ChromaDB metadata), never generated by the LLM",
    )
